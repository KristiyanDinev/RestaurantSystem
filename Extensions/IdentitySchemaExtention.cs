using System.Data;
using Microsoft.EntityFrameworkCore;
using RestaurantSystem.Database;

namespace RestaurantSystem.Extentions
{
    public static class IdentitySchemaExtention
    {
        public static async Task EnsureIdentitySchemaAsync(
            this DatabaseContext databaseContext,
            CancellationToken cancellationToken = default)
        {
            var connection = databaseContext.Database.GetDbConnection();
            if (connection.State != ConnectionState.Open)
            {
                await connection.OpenAsync(cancellationToken);
            }

            await using var command = connection.CreateCommand();
            command.CommandText = """
                ALTER TABLE IF EXISTS "Users"
                    ADD COLUMN IF NOT EXISTS "UserName" text,
                    ADD COLUMN IF NOT EXISTS "NormalizedUserName" text,
                    ADD COLUMN IF NOT EXISTS "NormalizedEmail" text,
                    ADD COLUMN IF NOT EXISTS "EmailConfirmed" boolean NOT NULL DEFAULT false,
                    ADD COLUMN IF NOT EXISTS "PasswordHash" text,
                    ADD COLUMN IF NOT EXISTS "SecurityStamp" text,
                    ADD COLUMN IF NOT EXISTS "ConcurrencyStamp" text,
                    ADD COLUMN IF NOT EXISTS "PhoneNumber" text,
                    ADD COLUMN IF NOT EXISTS "PhoneNumberConfirmed" boolean NOT NULL DEFAULT false,
                    ADD COLUMN IF NOT EXISTS "TwoFactorEnabled" boolean NOT NULL DEFAULT false,
                    ADD COLUMN IF NOT EXISTS "LockoutEnd" timestamp with time zone,
                    ADD COLUMN IF NOT EXISTS "LockoutEnabled" boolean NOT NULL DEFAULT false,
                    ADD COLUMN IF NOT EXISTS "AccessFailedCount" integer NOT NULL DEFAULT 0;

                UPDATE "Users"
                SET "UserName" = COALESCE(NULLIF("UserName", ''), "Email"),
                    "NormalizedUserName" = COALESCE(
                        NULLIF("NormalizedUserName", ''),
                        UPPER(COALESCE(NULLIF("UserName", ''), "Email"))),
                    "NormalizedEmail" = COALESCE(
                        NULLIF("NormalizedEmail", ''), UPPER("Email"))
                WHERE "UserName" IS NULL
                   OR "UserName" = ''
                   OR "NormalizedUserName" IS NULL
                   OR "NormalizedUserName" = ''
                   OR "NormalizedEmail" IS NULL
                   OR "NormalizedEmail" = '';

                DO $$
                BEGIN
                    IF EXISTS (
                        SELECT 1
                        FROM information_schema.columns
                        WHERE table_schema = 'public'
                          AND table_name = 'Users'
                          AND column_name = 'Password'
                    ) THEN
                        ALTER TABLE "Users" ALTER COLUMN "Password" DROP NOT NULL;
                    END IF;
                END $$;

                CREATE TABLE IF NOT EXISTS "AspNetRoles" (
                    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "Name" text NULL,
                    "NormalizedName" text NULL,
                    "ConcurrencyStamp" text NULL,
                    "Description" text NULL
                );

                CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "UserId" bigint NOT NULL,
                    "ClaimType" text NULL,
                    "ClaimValue" text NULL,
                    CONSTRAINT "FK_AspNetUserClaims_Users_UserId"
                        FOREIGN KEY ("UserId") REFERENCES "Users" ("Id") ON DELETE CASCADE
                );

                CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
                    "LoginProvider" text NOT NULL,
                    "ProviderKey" text NOT NULL,
                    "ProviderDisplayName" text NULL,
                    "UserId" bigint NOT NULL,
                    CONSTRAINT "PK_AspNetUserLogins" PRIMARY KEY ("LoginProvider", "ProviderKey"),
                    CONSTRAINT "FK_AspNetUserLogins_Users_UserId"
                        FOREIGN KEY ("UserId") REFERENCES "Users" ("Id") ON DELETE CASCADE
                );

                CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
                    "UserId" bigint NOT NULL,
                    "RoleId" bigint NOT NULL,
                    CONSTRAINT "PK_AspNetUserRoles" PRIMARY KEY ("UserId", "RoleId"),
                    CONSTRAINT "FK_AspNetUserRoles_Users_UserId"
                        FOREIGN KEY ("UserId") REFERENCES "Users" ("Id") ON DELETE CASCADE,
                    CONSTRAINT "FK_AspNetUserRoles_Roles_RoleId"
                        FOREIGN KEY ("RoleId") REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE
                );

                CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
                    "UserId" bigint NOT NULL,
                    "LoginProvider" text NOT NULL,
                    "Name" text NOT NULL,
                    "Value" text NULL,
                    CONSTRAINT "PK_AspNetUserTokens" PRIMARY KEY ("UserId", "LoginProvider", "Name"),
                    CONSTRAINT "FK_AspNetUserTokens_Users_UserId"
                        FOREIGN KEY ("UserId") REFERENCES "Users" ("Id") ON DELETE CASCADE
                );

                CREATE INDEX IF NOT EXISTS "RoleNameIndex"
                    ON "AspNetRoles" ("NormalizedName");
                CREATE INDEX IF NOT EXISTS "EmailIndex"
                    ON "Users" ("NormalizedEmail");
                CREATE UNIQUE INDEX IF NOT EXISTS "UserNameIndex"
                    ON "Users" ("NormalizedUserName");
                CREATE INDEX IF NOT EXISTS "IX_AspNetUserClaims_UserId"
                    ON "AspNetUserClaims" ("UserId");
                CREATE INDEX IF NOT EXISTS "IX_AspNetUserLogins_UserId"
                    ON "AspNetUserLogins" ("UserId");
                CREATE INDEX IF NOT EXISTS "IX_AspNetUserRoles_RoleId"
                    ON "AspNetUserRoles" ("RoleId");
                """;

            await command.ExecuteNonQueryAsync(cancellationToken);
        }
    }
}
